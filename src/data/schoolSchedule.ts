export const getBaseLessonsForClass = (className: string, dayName: string): [string, string][] => {
  const lessons = OFFICIAL_SCHEDULE_2026[className]?.[dayName];
  if (!lessons) return [];
  return lessons.map(([subject, room]) =>
    subject ? [subject, room || DEFAULT_ROOMS_BY_SUBJECT[subject] || ''] : ['—', ''],
  );
};

export const hasOfficialSchedule = (className: string): boolean => Boolean(OFFICIAL_SCHEDULE_2026[className]);
